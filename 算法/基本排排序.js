/**
 * 快速排序
 * 时间复杂度 O(nlogn)
 * 1、找一个基准（此处以数组的中间数为基准）；
 * 2、将大于基准的放在基准的左边数组中，小于基准的放在基准的右边数组中；
 * 2、将左边的数组和右边的数组不断重重复1,2步骤，直到数组中的元素只有一个；
 */

function kuaisupaixu(arr) {
  if (arr.length <= 1) {
    return arr;
  }
  // 基准数
  let mid = Math.floor(arr.length / 2);
  let pivot = arr[mid];
  // 去掉中间数，重新获取长度，让中间数和剩余的数进行对比
  arr.splice(mid, 1);
  // 左右数组用于分别存储小于基准的数，大于基准的数
  let left = [];
  let right = [];

  // 找到大于和小于基准的数
  for (let i = 0; i < arr.length; i++) {
    let ele = arr[i];
    if (ele > pivot) {
      right.push(ele);
    } else {
      left.push(ele);
    }
  }
  left = kuaisupaixu(left);
  right = kuaisupaixu(right);
  return [...left, pivot, ...right];
}
